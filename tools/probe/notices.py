#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the license of every crate compiled into the
probe's release binaries, with the license texts, as shipping a binary needs.

    tools/probe/notices.py           rewrite tools/probe/THIRD_PARTY_NOTICES.md
    tools/probe/notices.py --check   exit 1 if it is not current (CI)

The crates are those `cargo tree` links into the binary (normal dependencies,
not build scripts or proc macros) on any target in TARGETS, the release
targets of .github/workflows/probe.yml. Where a crate offers a choice of
licenses it is used under the first of PREFERENCE that it offers, and that
license's text is taken from the crate's own files (with its copyright
lines). Needs cargo and the crates fetched (cargo fetch).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "THIRD_PARTY_NOTICES.md"
TARGETS = [
    "x86_64-unknown-linux-musl",
    "aarch64-unknown-linux-musl",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
]
# The licenses chosen from an OR, most preferred first: short permissive texts.
PREFERENCE = ["MIT", "ISC", "BSD-3-Clause", "Zlib", "0BSD", "Apache-2.0", "Unicode-3.0", "Unlicense"]
# How a license file of a crate offering several names the license.
FILE_KEY = {"MIT": "mit", "Apache-2.0": "apache", "ISC": "isc", "Unicode-3.0": "unicode", "Zlib": "zlib",
            "0BSD": "0bsd", "Unlicense": "unlicense", "BSD-3-Clause": "bsd"}
# License files a crate keeps beside code it vendored, which its own files
# point to: ring's copy of once_cell (used under MIT, as once_cell is).
VENDORED = {"ring": ["src/polyfill/once_cell/LICENSE-MIT"]}
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|unlicense|notice)", re.I)

HEADER = """# Third-party notices: probe

The probe binary (`probe`, built from this directory) is licensed under the GNU General Public License v3.0 only (`GPL-3.0-only`, see [LICENSE](../../LICENSE)); its source, and the map engine it is built on (`frontend/engine`), are at https://github.com/868-no/map. It contains the third-party works below, all under licenses compatible with GPL-3.0.

## Data compiled in

| Component | Use | License |
|---|---|---|
| [Kartverket](https://www.kartverket.no/) county boundaries (2024), via [robhop/fylker-og-kommuner](https://github.com/robhop/fylker-og-kommuner), dissolved into regions (`frontend/src/assets/regions.geojson`) | health's region rules | CC BY 4.0, attribution "© Kartverket" |

Mesh data, terrain classes and the site's settings are fetched at run time from the deployment the probe is pointed at (default https://map.868.no) and are not part of the binary.

## Rust crates compiled in

Generated by `tools/probe/notices.py` from `Cargo.lock` for the release targets ({targets}). A crate offering a choice of licenses is used under the one named in the last column.

| Crate | Version | License | Used under |
|---|---|---|---|
"""

FOOTER = """
## Trademarks

Meshtastic® is a registered trademark of Meshtastic LLC. This project is not affiliated with or endorsed by Meshtastic LLC.
"""


def cargo(*args):
    return subprocess.run(["cargo", *args], cwd=HERE, check=True, capture_output=True, text=True).stdout


def linked():
    """(name, version) of every crate linked into the binary on some target."""
    out = set()
    for t in TARGETS:
        tree = cargo("tree", "--locked", "-e", "normal,no-proc-macro", "--target", t, "--prefix", "none", "--format", "{p}")
        for line in tree.splitlines():
            name, version = line.split()[:2]
            out.add((name, version.lstrip("v")))
    return out


def elect(expr):
    """The licenses a crate is used under: every AND term, the preferred of each OR."""
    chosen = []
    for term in re.split(r"\s+AND\s+", expr.strip()):
        options = [o.strip(" ()") for o in re.split(r"\s+OR\s+", term.strip(" ()"))]
        best = min(options, key=lambda o: PREFERENCE.index(o) if o in PREFERENCE else len(PREFERENCE))
        if best not in PREFERENCE:
            sys.exit(f"notices.py: no preference for license {best!r} in {expr!r}: add it to PREFERENCE")
        chosen.append(best)
    return chosen


def texts(name, version, root, chosen):
    """The crate's license files for the chosen licenses: the one naming each
    license, or else its files naming none (a single LICENSE, or ring's set)."""
    files = sorted(p for p in root.iterdir() if p.is_file() and LICENSE_FILE.match(p.name))
    named = lambda p, key: key in p.name.lower().replace("-", "").replace("_", "")
    generic = [p for p in files if not any(named(p, k) for k in FILE_KEY.values())]
    picked = []
    for lic in chosen:
        own = [p for p in files if named(p, FILE_KEY[lic])]
        for p in own or generic:
            if p not in picked:
                picked.append(p)
    picked += [root / f for f in VENDORED.get(name, [])]
    if not picked:
        sys.exit(f"notices.py: no license file for {name} {version} ({', '.join(chosen)}) in {root}")
    return [p.read_text(encoding="utf-8", errors="replace").strip() for p in picked]


def render():
    meta = json.loads(cargo("metadata", "--locked", "--format-version", "1"))
    want = linked()
    crates = []
    for pkg in meta["packages"]:
        if (pkg["name"], pkg["version"]) not in want or pkg["source"] is None:
            continue  # not linked, or our own (the probe, the engine)
        expr = pkg.get("license") or sys.exit(f"notices.py: {pkg['name']} names no license")
        chosen = elect(expr)
        crates.append((pkg["name"], pkg["version"], expr, chosen, texts(pkg["name"], pkg["version"], Path(pkg["manifest_path"]).parent, chosen)))
    crates.sort(key=lambda c: (c[0], c[1]))

    out = [HEADER.format(targets=", ".join(TARGETS))]
    for name, version, expr, chosen, _ in crates:
        out.append(f"| [{name}](https://crates.io/crates/{name}/{version}) | {version} | {expr} | {' AND '.join(chosen)} |\n")
    # Identical texts once, with the crates they cover.
    groups = {}
    for name, version, _, _, ts in crates:
        for t in ts:
            groups.setdefault(t, []).append(f"{name} {version}")
    out.append("\n## License texts\n")
    for i, (text, users) in enumerate(sorted(groups.items(), key=lambda g: g[1][0]), 1):
        fence = "````" if "```" in text else "```"
        out.append(f"\n### Text {i}\n\nUsed by: {', '.join(users)}\n\n{fence}text\n{text}\n{fence}\n")
    out.append(FOOTER)
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is not current: run tools/probe/notices.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
